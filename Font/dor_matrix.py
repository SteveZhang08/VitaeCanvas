def string_to_coordinates(text, spacing=1):
    """
    将整个字符串转换为坐标列表
    
    参数:
        text: 要转换的字符串
        spacing: 字符之间的间距 (默认1)
    
    返回:
        list: 包含所有字符坐标的列表，每个坐标是[x, y]形式
    """
    all_coordinates = []
    
    for i, char in enumerate(text):
        # 获取单个字符的坐标
        char_coords = char_to_coordinates(char)
        
        # 计算字符的水平偏移（考虑字符间距）
        x_offset = i * (5 + spacing)
        
        # 调整每个点的x坐标
        for coord in char_coords:
            adjusted_coord = [coord[0] + x_offset, coord[1]]
            all_coordinates.append(adjusted_coord)
    
    return all_coordinates


def visualize_coordinates(coordinates, width=None, height=None):
    """
    可视化坐标点（用于测试和显示）
    
    参数:
        coordinates: 坐标列表
        width: 显示宽度（自动计算如果为None）
        height: 显示高度（固定为7）
    
    返回:
        str: 可视化字符串
    """
    if not coordinates:
        return ""
    
    # 计算边界
    if width is None:
        max_x = max(coord[0] for coord in coordinates)
        width = max_x + 1
    if height is None:
        max_y = max(coord[1] for coord in coordinates)
        height = max_y + 1
    
    # 创建空白画布
    canvas = [[' ' for _ in range(width)] for _ in range(height)]
    
    # 填充点
    for x, y in coordinates:
        if 0 <= x < width and 0 <= y < height:
            canvas[y][x] = '█'
    
    # 转换为字符串
    result = []
    for row in canvas:
        result.append(''.join(row))
    
    return '\n'.join(result)


