def string_to_coordinates(text, spacing=1):
    """
    将整个字符串转换为坐标列表
    
    参数:
        text: 要转换的字符串
        spacing: 字符之间的间距 (默认1)
    
    返回:
        list: 包含所有字符坐标的列表，每个坐标是[x, y]形式
    """
    all_coordinates = []
    
    for i, char in enumerate(text):
        # 获取单个字符的坐标
        char_coords = char_to_coordinates(char)
        
        # 计算字符的水平偏移（考虑字符间距）
        x_offset = i * (5 + spacing)
        
        # 调整每个点的x坐标
        for coord in char_coords:
            adjusted_coord = [coord[0] + x_offset, coord[1]]
            all_coordinates.append(adjusted_coord)
    
    return all_coordinates

